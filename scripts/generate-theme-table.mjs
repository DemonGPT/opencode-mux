#!/usr/bin/env node
// Regenerates src/theme/builtin.ts from the opencode v2.0.5 theme assets.
// Usage:
//   node scripts/generate-theme-table.mjs                 # fetch from GitHub
//   node scripts/generate-theme-table.mjs --from <dir>    # read local assets
// Exits non-zero (without writing) if any theme fails to resolve.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ASSET_URL = "https://raw.githubusercontent.com/anomalyco/opencode/v2.0.5/packages/tui/src/theme/assets/<name>.json";
const OUT_FILE = fileURLToPath(new URL("../src/theme/builtin.ts", import.meta.url));

// The 33 built-in themes shipped in the opencode v2.0.5 TUI.
const THEME_NAMES = [
  "aura",
  "ayu",
  "carbonfox",
  "catppuccin",
  "catppuccin-frappe",
  "catppuccin-macchiato",
  "cobalt2",
  "cursor",
  "dracula",
  "everforest",
  "flexoki",
  "github",
  "gruvbox",
  "kanagawa",
  "lucent-orng",
  "material",
  "matrix",
  "mercury",
  "monokai",
  "nightowl",
  "nord",
  "one-dark",
  "opencode",
  "orng",
  "osaka-jade",
  "palenight",
  "rosepine",
  "solarized",
  "synthwave84",
  "tokyonight",
  "vercel",
  "vesper",
  "zenburn",
].sort();

// --- v1 flat theme resolution (prototype logic, verified against all 33) ---

const isHex = (v) => typeof v === "string" && /^#[0-9a-fA-F]{3,8}$/.test(v);

function normHex(v) {
  let h = v.slice(1);
  if (h.length === 3) h = h.split("").map((c) => c + c).join("");
  else if (h.length === 4) h = h.slice(0, 3).split("").map((c) => c + c).join("");
  else if (h.length === 8) h = h.slice(0, 6);
  return h.length === 6 ? `#${h.toLowerCase()}` : null;
}

function resolve(value, theme, defs, mode, depth = 0) {
  if (depth > 8 || value === null || value === undefined) return null;
  if (typeof value === "number") return { ansi: value };
  if (typeof value !== "string") return null;
  if (isHex(value)) {
    const hex = normHex(value);
    return hex === null ? null : { hex };
  }
  if (value === "none" || value === "transparent") return null;
  const next = defs[value] ?? theme[value];
  if (next === undefined) return null;
  if (typeof next === "object" && next !== null && ("dark" in next || "light" in next)) {
    return resolve(next[mode] ?? next.dark, theme, defs, mode, depth + 1);
  }
  return resolve(next, theme, defs, mode, depth + 1);
}

function pick(value, theme, defs, mode) {
  if (value === null || value === undefined) return null;
  if (typeof value === "object" && !Array.isArray(value)) {
    return resolve(value[mode] ?? value.dark, theme, defs, mode);
  }
  return resolve(value, theme, defs, mode);
}

function toColor(resolved) {
  if (resolved === null) return null;
  return resolved.hex !== undefined ? resolved.hex : `colour${resolved.ansi}`;
}

function resolveAsset(doc) {
  const theme = doc.theme ?? doc;
  const defs = doc.defs ?? {};
  const entry = {};
  for (const mode of ["dark", "light"]) {
    const inactive = toColor(pick(theme.border, theme, defs, mode));
    const active = toColor(pick(theme.borderActive ?? theme.border, theme, defs, mode));
    entry[mode] = { inactive, active };
  }
  return entry;
}

// --- asset loading ---

function loadLocal(names, dir) {
  return new Map(
    names.map((name) => {
      const file = `${dir}/${name}.json`;
      return [name, JSON.parse(readFileSync(file, "utf8"))];
    }),
  );
}

async function loadRemote(names, urlTemplate) {
  const entries = await Promise.all(
    names.map(async (name) => {
      const url = urlTemplate.replace("<name>", name);
      const response = await fetch(url);
      if (!response.ok) throw new Error(`GET ${url} -> ${response.status}`);
      return [name, await response.json()];
    }),
  );
  return new Map(entries);
}

// --- emit ---

function emitTable(entries) {
  const lines = [
    "// Generated by scripts/generate-theme-table.mjs — do not edit by hand.",
    "// Source: anomalyco/opencode@v2.0.5, packages/tui/src/theme/assets/*.json (MIT).",
    "// Regenerate: node scripts/generate-theme-table.mjs",
    "",
    "export const BUILTIN_THEME_BORDERS: Record<",
    "  string,",
    "  { dark: { inactive: string; active: string }; light: { inactive: string; active: string } }",
    "> = {",
  ];
  for (const name of [...entries.keys()].sort()) {
    lines.push(`  ${JSON.stringify(name)}: ${JSON.stringify(entries.get(name))},`);
  }
  lines.push("};", "");
  return lines.join("\n");
}

// --- main ---

async function main() {
  const fromIndex = process.argv.indexOf("--from");
  const fromDir = fromIndex !== -1 ? process.argv[fromIndex + 1] : undefined;

  let docs;
  if (fromDir !== undefined) {
    docs = loadLocal(THEME_NAMES, fromDir);
  } else {
    docs = await loadRemote(THEME_NAMES, ASSET_URL);
  }

  const entries = new Map();
  const problems = [];
  for (const name of THEME_NAMES) {
    const doc = docs.get(name);
    if (doc === undefined) {
      problems.push(`${name}: asset missing`);
      continue;
    }
    const entry = resolveAsset(doc);
    for (const mode of ["dark", "light"]) {
      if (entry[mode].inactive === null || entry[mode].active === null) problems.push(`${name}.${mode}`);
    }
    entries.set(name, entry);
  }

  console.log(`themes resolved: ${entries.size}/${THEME_NAMES.length}`);
  for (const name of [...entries.keys()].sort()) {
    const e = entries.get(name);
    console.log(`  ${name}: ${e.dark.inactive}/${e.dark.active} | ${e.light.inactive}/${e.light.active}`);
  }
  if (problems.length > 0) {
    console.error(`unresolved: ${problems.join(", ")}`);
    process.exit(1);
  }
  mkdirSync(dirname(OUT_FILE), { recursive: true });
  writeFileSync(OUT_FILE, emitTable(entries), "utf8");
  console.log(`wrote ${OUT_FILE}`);
}

main().catch((error) => {
  console.error(`generate-theme-table: ${error.message}`);
  process.exit(1);
});